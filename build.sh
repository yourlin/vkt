# Builds vkt for Android arm64 (API level 29): the shaders with
# glslangValidator and spirv-as, the program with the NDK's clang.
#
#   ./build.sh
#
# Environment:
#   ANDROID_NDK_HOME  the Android NDK (r28c tested); ANDROID_NDK_ROOT or NDK
#                     also work
#   VULKAN_INCLUDE    a directory with vulkan/vulkan.h (Vulkan-Headers 1.3 or
#                     later); default: the first of $VULKAN_SDK/include,
#                     /opt/homebrew/include, /usr/local/include, /usr/include
#                     that has it
#   CC                the compiler, instead of the NDK's
#
# Output: build/vkt.
set -e
cd "$(dirname "$0")"

die() {
   echo "build.sh: $*" >&2
   exit 1
}

NDK=${ANDROID_NDK_HOME:-${ANDROID_NDK_ROOT:-${NDK:-}}}
if [ -z "$CC" ]; then
   [ -n "$NDK" ] || die "set ANDROID_NDK_HOME to the Android NDK"
   case "$(uname -s)" in
   Darwin) host=darwin-x86_64 ;;
   *) host=linux-x86_64 ;;
   esac
   CC=$NDK/toolchains/llvm/prebuilt/$host/bin/aarch64-linux-android29-clang
   [ -x "$CC" ] || die "no compiler at $CC"
fi

if [ -z "$VULKAN_INCLUDE" ]; then
   for d in ${VULKAN_SDK:+$VULKAN_SDK/include} /opt/homebrew/include /usr/local/include /usr/include; do
      if [ -f "$d/vulkan/vulkan.h" ]; then
         VULKAN_INCLUDE=$d
         break
      fi
   done
fi
[ -f "$VULKAN_INCLUDE/vulkan/vulkan.h" ] ||
   die "no vulkan/vulkan.h; install Vulkan-Headers or set VULKAN_INCLUDE"

for tool in glslangValidator spirv-as spirv-val python3; do
   command -v $tool >/dev/null || die "$tool not found"
done

mkdir -p build
for s in shaders/*; do
   b=$(basename "$s")
   n=$(echo "$b" | tr . _)
   case "$b" in
   *.spvasm)
      n=${n%_spvasm}
      spirv-as --target-env vulkan1.1 -o "build/$n.spv" "$s"
      spirv-val --target-env vulkan1.1 "build/$n.spv"
      ;;
   *)
      glslangValidator -V --target-env vulkan1.1 -o "build/$n.spv" "$s" >build/glslang.log 2>&1 || {
         cat build/glslang.log
         exit 1
      }
      ;;
   esac
done

# The SPIR-V as C arrays, one per shader, named after the file
# (shaders/t3_cull.vert: t3_cull_vert).
python3 - build/shaders.h build/*.spv <<'PY'
import os, struct, sys
out = open(sys.argv[1], "w")
out.write("/* Generated by build.sh from shaders/. */\n#include <stdint.h>\n")
for p in sys.argv[2:]:
    d = open(p, "rb").read()
    w = struct.unpack("<%dI" % (len(d) // 4), d)
    name = os.path.basename(p)[:-4]
    out.write("static const uint32_t %s[] = {\n" % name)
    for i in range(0, len(w), 8):
        out.write("   " + ", ".join("0x%08x" % x for x in w[i:i + 8]) + ",\n")
    out.write("};\n")
PY

"$CC" -O2 -Wall -Wextra -Wno-unused-parameter -Wno-unused-function -std=c11 \
   -D_POSIX_C_SOURCE=200809L -I"$VULKAN_INCLUDE" -Ibuild -o build/vkt vkt.c -ldl -lm
echo "built build/vkt"
